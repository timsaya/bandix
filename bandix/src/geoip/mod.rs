#[cfg(test)]
mod tests;
use anyhow::{bail, Context, Result};
use database::Database;
use model::*;
pub use model::{GeoInfo, Profile, Status, UPLOAD_PATH};
use std::{
    collections::{HashMap, VecDeque},
    fs,
    io::Write,
    net::IpAddr,
    path::{Path, PathBuf},
    sync::{
        atomic::{AtomicBool, Ordering},
        Arc, Mutex,
    },
};
use tokio::sync::Notify;

pub struct GeoIpManager {
    directory: PathBuf,
    state: Mutex<State>,
}
struct State {
    settings: Settings,
    databases: Vec<Database>,
    job: Job,
    cancel: Option<Arc<Cancel>>,
    load_error: Option<String>,
    cache: HashMap<IpAddr, GeoInfo>,
    order: VecDeque<IpAddr>,
}
pub(super) struct Cancel {
    requested: AtomicBool,
    notify: Notify,
}
impl Cancel {
    fn new() -> Self {
        Self {
            requested: AtomicBool::new(false),
            notify: Notify::new(),
        }
    }
    fn check(&self) -> Result<()> {
        if self.requested.load(Ordering::Relaxed) {
            bail!("Download cancelled");
        }
        Ok(())
    }
}
impl GeoIpManager {
    pub fn new(directory: PathBuf) -> Arc<Self> {
        let loaded = (|| -> Result<(Settings, Vec<Database>)> {
            let bytes = match fs::read(directory.join("state.json")) {
                Ok(bytes) => bytes,
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok((Settings::default(), Vec::new())),
                Err(error) => return Err(error.into()),
            };
            let settings: Settings = serde_json::from_slice(&bytes)?;
            let databases = load_databases(&directory, &settings)?;
            Ok((settings, databases))
        })();
        let (settings, databases, load_error) = match loaded {
            Ok((settings, databases)) => (settings, databases, None),
            Err(error) => {
                log::warn!("GeoIP database unavailable: {error:#}");
                (Settings::default(), Vec::new(), Some(format!("{error:#}")))
            }
        };
        // Only names generated by this manager are eligible for stale staging cleanup.
        // Committed generations other than the current one may be left by a power loss.
        if load_error.is_none() {
            if let Err(error) = prune_generations(&directory, settings.active.as_deref()) {
                log::debug!("Cannot clean old GeoIP files: {error:#}");
            }
        }
        Arc::new(Self {
            directory,
            state: Mutex::new(State {
                settings,
                databases,
                load_error,
                job: Job::default(),
                cancel: None,
                cache: HashMap::new(),
                order: VecDeque::new(),
            }),
        })
    }
    pub fn status(&self) -> Status {
        let state = self.state.lock().unwrap();
        Status {
            enabled: state.settings.enabled,
            profile: state.settings.profile,
            directory: self.directory.display().to_string(),
            free_bytes: available_bytes(&self.directory).ok(),
            installed_bytes: state.databases.iter().map(|db| db.info.bytes).sum(),
            version: state.settings.version.clone(),
            source: state.settings.source.clone(),
            databases: state.databases.iter().map(|db| db.info.clone()).collect(),
            job: state.job.clone(),
            load_error: state.load_error.clone(),
            upload_path: UPLOAD_PATH,
            upload_max_bytes: upload_limit(),
        }
    }
    pub fn enabled(&self) -> bool {
        self.state.lock().unwrap().settings.enabled
    }
    pub fn lookup(&self, ip: IpAddr, local: bool) -> GeoInfo {
        if local {
            return GeoInfo::scope("local");
        }
        let ip = database::normalize(ip);
        if let Some(scope) = database::special_scope(ip) {
            return GeoInfo::scope(scope);
        }
        let mut state = self.state.lock().unwrap();
        if !state.settings.enabled {
            return GeoInfo::scope("unknown");
        }
        if let Some(result) = state.cache.get(&ip) {
            return result.clone();
        }
        let result = database::lookup(&state.databases, ip);
        if state.cache.len() >= CACHE_ENTRIES {
            if let Some(oldest) = state.order.pop_front() {
                state.cache.remove(&oldest);
            }
        }
        state.cache.insert(ip, result.clone());
        state.order.push_back(ip);
        result
    }
    pub fn set_enabled(&self, enabled: bool) -> Result<()> {
        let mut state = self.state.lock().unwrap();
        if state.job.busy {
            bail!("A database task is already running");
        }
        if enabled && state.databases.is_empty() {
            bail!("Download or upload a database first");
        }
        let mut settings = state.settings.clone();
        settings.enabled = enabled;
        self.write_settings(&settings)?;
        state.settings = settings;
        Ok(())
    }
    pub fn delete(&self) -> Result<()> {
        let mut state = self.state.lock().unwrap();
        if state.job.busy {
            bail!("A database task is already running");
        }
        self.write_settings(&Settings::default())?;
        state.settings = Settings::default();
        state.databases.clear();
        state.cache.clear();
        state.order.clear();
        state.load_error = None;
        state.job = Job::default();
        // Only directories generated by this manager are eligible for removal.
        if let Err(error) = prune_generations(&self.directory, None) {
            state.load_error = Some(format!("Cannot remove database files: {error:#}"));
            return Err(error);
        }
        Ok(())
    }
    pub fn cancel(&self) -> Result<()> {
        let state = self.state.lock().unwrap();
        if state.job.phase == "activating" {
            bail!("The database is being activated; please wait");
        }
        if let Some(cancel) = &state.cancel {
            cancel.requested.store(true, Ordering::Relaxed);
            cancel.notify.notify_one();
        }
        Ok(())
    }
    pub fn start_download(self: &Arc<Self>, profile: Profile) -> Result<()> {
        let cancel = self.begin_job("preparing")?;
        self.state.lock().unwrap().job.profile = Some(profile);
        let manager = self.clone();
        tokio::spawn(async move {
            let result = tokio::select! {
                result = manager.download(profile, &cancel) => result,
                _ = cancel.notify.notified() => Err(anyhow::anyhow!("Download cancelled")),
            };
            manager.finish_preparation(result, cancel).await;
        });
        Ok(())
    }
    pub fn start_import(self: &Arc<Self>) -> Result<()> {
        let cancel = match self.begin_job("importing") {
            Ok(cancel) => cancel,
            Err(error) => {
                let _ = fs::remove_file(UPLOAD_PATH);
                return Err(error);
            }
        };
        let manager = self.clone();
        tokio::spawn(async move {
            let result = tokio::select! {
                result = manager.import(&cancel) => result,
                _ = cancel.notify.notified() => Err(anyhow::anyhow!("Upload import cancelled")),
            };
            manager.finish_preparation(result.map(Some), cancel).await;
            let _ = fs::remove_file(UPLOAD_PATH);
        });
        Ok(())
    }
    fn begin_job(&self, phase: &str) -> Result<Arc<Cancel>> {
        let mut state = self.state.lock().unwrap();
        if state.job.busy {
            bail!("A database task is already running");
        }
        fs::create_dir_all(&self.directory).context("Cannot create database directory")?;
        let cancel = Arc::new(Cancel::new());
        state.job = Job {
            id: state.job.id.wrapping_add(1),
            busy: true,
            phase: phase.into(),
            ..Job::default()
        };
        state.cancel = Some(cancel.clone());
        Ok(cancel)
    }
    pub(super) fn phase(&self, phase: &str) {
        self.state.lock().unwrap().job.phase = phase.into();
    }
    pub(super) fn progress(&self, bytes: u64) {
        self.state.lock().unwrap().job.downloaded_bytes += bytes;
    }
    async fn finish_preparation(self: &Arc<Self>, result: Result<Option<download::Prepared>>, cancel: Arc<Cancel>) {
        let result = match result {
            Ok(None) => Ok(false),
            Ok(Some(prepared)) => {
                let commit = {
                    let mut state = self.state.lock().unwrap();
                    if cancel.requested.load(Ordering::Relaxed) {
                        false
                    } else {
                        state.job.phase = "activating".into();
                        true
                    }
                };
                if commit {
                    let manager = self.clone();
                    tokio::task::spawn_blocking(move || manager.activate(prepared).map(|_| true))
                        .await
                        .unwrap_or_else(|error| Err(error.into()))
                } else {
                    Err(anyhow::anyhow!("Download cancelled"))
                }
            }
            Err(error) => Err(error),
        };
        let mut state = self.state.lock().unwrap();
        state.job.busy = false;
        state.cancel = None;
        match result {
            Ok(changed) => {
                state.job.phase = if changed { "completed" } else { "up_to_date" }.into();
                state.job.error = None;
            }
            Err(error) => {
                state.job.error_phase = Some(state.job.phase.clone());
                state.job.phase = if cancel.requested.load(Ordering::Relaxed) { "cancelled" } else { "failed" }.into();
                state.job.error = Some(format!("{error:#}"));
            }
        }
    }
    fn activate(&self, prepared: download::Prepared) -> Result<()> {
        let name = format!("db-{}", uuid::Uuid::new_v4());
        let path = self.directory.join(&name);
        // Persist an immutable generation first. The atomic settings file is the
        // commit point; startup only opens the generation referenced there.
        for kind in prepared.profile.files() {
            fs::File::open(prepared.directory.path().join(kind.filename()))?.sync_all()?;
        }
        fs::File::open(prepared.directory.path())?.sync_all()?;
        fs::rename(prepared.directory.path(), &path).context("Cannot install downloaded database")?;
        let enabled = {
            let state = self.state.lock().unwrap();
            state.databases.is_empty() || state.settings.enabled
        };
        let settings = Settings {
            enabled,
            profile: prepared.profile,
            active: Some(name),
            version: prepared.version,
            source: prepared.source,
        };
        let commit = (|| -> Result<_> {
            let databases = load_databases(&self.directory, &settings)?;
            self.write_settings(&settings)?;
            let mut state = self.state.lock().unwrap();
            let active = settings.active.clone().unwrap();
            state.settings = settings;
            state.databases = databases;
            state.cache.clear();
            state.order.clear();
            state.load_error = None;
            Ok(active)
        })();
        match commit {
            Ok(active) => {
                if let Err(error) = prune_generations(&self.directory, Some(&active)) {
                    log::warn!("Cannot remove old GeoIP generations: {error:#}");
                }
                Ok(())
            }
            Err(error) => {
                let _ = fs::remove_dir_all(path);
                Err(error)
            }
        }
    }
    fn write_settings(&self, settings: &Settings) -> Result<()> {
        fs::create_dir_all(&self.directory)?;
        let mut temporary = tempfile::NamedTempFile::new_in(&self.directory)?;
        serde_json::to_writer_pretty(temporary.as_file_mut(), settings)?;
        temporary.write_all(b"\n")?;
        temporary.as_file().sync_all()?;
        temporary.persist(self.directory.join("state.json"))?;
        // The rename above is already the commit point. A directory fsync
        // failure must not make the caller delete a now-referenced generation.
        if let Err(error) = fs::File::open(&self.directory).and_then(|file| file.sync_all()) {
            log::warn!("Cannot sync GeoIP directory: {error}");
        }
        Ok(())
    }
}
fn load_databases(directory: &Path, settings: &Settings) -> Result<Vec<Database>> {
    let Some(active) = &settings.active else {
        if settings.enabled {
            bail!("No database is installed");
        }
        return Ok(Vec::new());
    };
    if !valid_generation(active) {
        bail!("Invalid database generation directory");
    }
    if !fs::symlink_metadata(directory.join(active))?.is_dir() {
        bail!("Invalid database generation");
    }
    settings
        .profile
        .files()
        .iter()
        .map(|kind| Database::open(&directory.join(active).join(kind.filename()), Some(*kind), false))
        .collect()
}
fn valid_generation(value: &str) -> bool {
    value.starts_with("db-") && value.len() == 39 && uuid::Uuid::parse_str(&value[3..]).is_ok()
}
fn prune_generations(directory: &Path, keep: Option<&str>) -> Result<()> {
    let entries = match fs::read_dir(directory) {
        Ok(entries) => entries,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(error.into()),
    };
    for entry in entries {
        let entry = entry?;
        let name = entry.file_name().to_string_lossy().into_owned();
        let staging = name
            .strip_prefix(".download-")
            .is_some_and(|suffix| suffix.len() == 6 && suffix.bytes().all(|c| c.is_ascii_alphanumeric()));
        if (valid_generation(&name) || staging) && keep != Some(name.as_str()) {
            if entry.file_type()?.is_dir() {
                fs::remove_dir_all(entry.path())?;
            } else {
                fs::remove_file(entry.path())?;
            }
        }
    }
    Ok(())
}
pub(super) fn available_bytes(path: &Path) -> Result<u64> {
    use std::{ffi::CString, os::unix::ffi::OsStrExt};
    let mut existing = path;
    while !existing.exists() {
        existing = existing.parent().context("Cannot find storage directory")?;
    }
    let path = CString::new(existing.as_os_str().as_bytes())?;
    let mut info = std::mem::MaybeUninit::<libc::statvfs>::uninit();
    // SAFETY: path is NUL terminated and info points to writable statvfs storage.
    if unsafe { libc::statvfs(path.as_ptr(), info.as_mut_ptr()) } != 0 {
        return Err(std::io::Error::last_os_error().into());
    }
    let info = unsafe { info.assume_init() };
    Ok((info.f_bavail as u64).saturating_mul(info.f_frsize as u64))
}

// Browser uploads use OpenWrt's temporary upload area. Advertise a conservative
// cap before transferring the file, so a large City file cannot exhaust RAM.
fn upload_limit() -> u64 {
    fs::read_to_string("/proc/meminfo")
        .ok()
        .and_then(|text| {
            text.lines().find_map(|line| {
                line.strip_prefix("MemAvailable:")
                    .and_then(|value| value.split_whitespace().next())
                    .and_then(|value| value.parse::<u64>().ok())
            })
        })
        .map(|kib| (kib.saturating_mul(1024) / 2).min(MAX_FILE_BYTES))
        .unwrap_or(8 * 1024 * 1024)
}
